export function languageFor(value) {
  return value === "de" ? "de" : "en";
}

export function t(language, key, values = {}) {
  const lang = languageFor(language);
  const template = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function applyI18n(root, language) {
  const lang = languageFor(language);
  root.documentElement.lang = lang;
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(lang, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(lang, element.dataset.i18nAria));
  });
  const description = root.querySelector('meta[name="description"]');
  if (description) description.content = t(lang, "meta.description");
}
